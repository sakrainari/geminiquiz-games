// Create the independent Codex question file from the maintained quiz sources.
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(root,'question-bank.js'),'utf8'),context);
const html = fs.readFileSync(path.join(root,'voice_answer_quiz.html'),'utf8');
vm.runInContext(html.slice(html.indexOf('const BUILTIN_QUIZZES'),html.indexOf('class SoundEffects')),context);
const packs = vm.runInContext('BUILTIN_QUIZZES',context);
const questions = Object.entries(packs).flatMap(([category,pack]) => pack.questions.map(q => ({
  id: category + '-' + crypto.createHash('sha256').update(q.q).digest('hex').slice(0,12),
  category, ...q
})));
fs.mkdirSync(path.join(root,'codex'),{recursive:true});
fs.writeFileSync(path.join(root,'codex/questions.js'),
  '// Generated by node scripts/build-codex-data.cjs. Edit the maintained sources first.\nconst CODEX_QUESTIONS = ' + JSON.stringify(questions,null,2) + ';\n');
console.log(`Codex question bank: ${questions.length} questions`);
